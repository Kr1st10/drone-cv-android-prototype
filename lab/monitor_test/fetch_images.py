#!/usr/bin/env python3
"""Download the Stage 6.6 lab test images listed in manifest.json and verify SHA-256.

Standard library only (Python 3.8+). Images are not stored in the repository: they are fetched
from their original source (Wikimedia Commons originals) into ./images/ next to this script.

    python3 fetch_images.py            # download missing files, verify all
    python3 fetch_images.py --verify   # only verify existing files
    python3 fetch_images.py --original # fallback: full-size originals, verified by Commons SHA-1

By default the 3840-px standard thumbnails (or the original when it is narrower) are fetched and
checked against manifest sha256. Wikimedia may in rare cases regenerate a thumbnail; then use
--original. The gallery positions objects in manifest coordinates (width/height), so an original
of a different resolution but the same aspect ratio is displayed identically.
"""
import argparse, hashlib, json, sys, time, urllib.parse, urllib.request
from pathlib import Path

HERE = Path(__file__).resolve().parent
UA = 'drone-cv-lab-test/1.0 (university lab test set; https://github.com/Kr1st10/drone-cv-android-prototype)'


def expand(m):
    """Derive file name and Wikimedia URLs from the compact manifest entry (commons_file, ext, thumb3840)."""
    name = m['commons_file'].replace(' ', '_')
    h = hashlib.md5(name.encode('utf-8')).hexdigest()
    q = urllib.parse.quote(name, safe="-_.~!*';:@=+$")  # upload/thumb paths: ',', '&', '(' ')' encoded
    p = urllib.parse.quote(name, safe="-_.~!*'(),;:@=+$")  # wiki page path
    t = 'thumbnail' + m['ext'] if len(name.encode('utf-8')) > 160 else q  # MediaWiki shortens long thumb names
    e = dict(m)
    e['file'] = f"images/{m['id']}{m['ext']}"
    e['original_url'] = f'https://upload.wikimedia.org/wikipedia/commons/{h[0]}/{h[:2]}/{q}'
    e['download_url'] = (f'https://thumb.wikimedia.org/wikipedia/commons/thumb/{h[0]}/{h[:2]}/{q}/3840px-{t}'
                         if m['thumb3840'] else e['original_url'])
    e['source_page'] = 'https://commons.wikimedia.org/wiki/File:' + p
    e['label'] = m['commons_file'].rsplit('.', 1)[0]
    return e


def write_manifest_js(man_path, out_path=None):
    """manifest.js = expanded manifest for gallery.html (browsers do not let file:// pages read JSON)."""
    text = Path(man_path).read_text(encoding='utf-8'); man = json.loads(text)
    man = dict(man, images=[expand(m) for m in man['images']])
    js = ('// Generated by fetch_images.py / build_manifest.py from manifest.json - do not edit.\n'
          f'window.MANIFEST_SHA256 = "{hashlib.sha256(text.encode("utf-8")).hexdigest()}";\n'
          f'window.MANIFEST = {json.dumps(man, ensure_ascii=False)};\n')
    out = Path(out_path or Path(man_path).with_name('manifest.js'))
    out.write_text(js, encoding='utf-8'); return out


def digest(p, algo='sha256'):
    h = hashlib.new(algo)
    with open(p, 'rb') as f:
        for b in iter(lambda: f.read(1 << 20), b''): h.update(b)
    return h.hexdigest()


def fetch(url, dest, tries=6):
    tmp = dest.with_suffix(dest.suffix + '.part')
    for k in range(tries):
        try:
            req = urllib.request.Request(url, headers={'User-Agent': UA})
            with urllib.request.urlopen(req, timeout=120) as r, open(tmp, 'wb') as f:
                while True:
                    b = r.read(1 << 20)
                    if not b: break
                    f.write(b)
            tmp.replace(dest); return True
        except Exception as e:  # 429/5xx/network: back off and retry
            wait = min(120, 5 * 2 ** k); print(f'  retry in {wait}s: {e}', flush=True); time.sleep(wait)
    return False


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--manifest', type=Path, default=HERE / 'manifest.json')
    ap.add_argument('--verify', action='store_true', help='do not download, only verify')
    ap.add_argument('--original', action='store_true', help='download originals, verify Commons SHA-1')
    ap.add_argument('--delay', type=float, default=1.0, help='pause between downloads, s')
    a = ap.parse_args(argv)
    man = json.loads(a.manifest.read_text(encoding='utf-8')); root = a.manifest.parent
    print('wrote', write_manifest_js(a.manifest).name)
    man['images'] = [expand(m) for m in man['images']]
    ok, bad, missing = 0, [], []
    for i, m in enumerate(man['images'], 1):
        dest = root / m['file']; dest.parent.mkdir(parents=True, exist_ok=True)
        good = lambda: digest(dest) == m['sha256'] or (a.original and digest(dest, 'sha1') == m['original_sha1'])
        if dest.exists() and good(): ok += 1; continue
        if a.verify: (bad if dest.exists() else missing).append(m['id']); continue
        url = m['original_url'] if a.original else m['download_url']
        print(f'[{i}/{len(man["images"])}] {m["id"]} <- {url}', flush=True)
        if not fetch(url, dest): missing.append(m['id']); continue
        if not good():
            bad.append(m['id']); dest.rename(dest.with_suffix('.sha256-mismatch')); print('  checksum mismatch, file renamed (try --original)', flush=True)
        else: ok += 1
        time.sleep(a.delay)
    print(f'OK {ok} / {len(man["images"])}; mismatch {len(bad)}; missing {len(missing)}')
    if bad: print('mismatch:', ', '.join(bad))
    if missing: print('missing:', ', '.join(missing))
    if not bad and not missing: print('Ready: open gallery.html in a browser (offline).')
    return 0 if not bad and not missing else 1


if __name__ == '__main__':
    sys.exit(main())
